function score(
  applicationId: string,
  evaluatorId: string,
  marks: [number, number, number, number, number, number],
  on: string,
  comment = '',
): Score {
  const [impact, feasibility, innovation, value, scalability, team] = marks
  return {
    id: `sc-${applicationId}-${evaluatorId}`,
    applicationId,
    evaluatorId,
    marks: { impact, feasibility, innovation, value, scalability, team },
    comment,
    conflictDeclared: true,
    submittedOn: on,
  }
}

