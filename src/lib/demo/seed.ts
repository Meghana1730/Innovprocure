function milestone(
  challenge: string,
  order: number,
  title: string,
  deliverable: string,
  dueOn: string,
  paymentPct: number,
  valueLakh: number,
  dates: Partial<
    Pick<Milestone, 'submittedOn' | 'acceptedOn' | 'requestedOn' | 'approvedOn' | 'paidOn'>
  > = {},
): Milestone {
  const status: Milestone['status'] = dates.acceptedOn
    ? 'ACCEPTED'
    : dates.submittedOn
      ? 'SUBMITTED'
      : 'PLANNED'
  const payment: Milestone['payment'] = dates.paidOn
    ? 'PAID'
    : dates.approvedOn
      ? 'APPROVED'
      : dates.requestedOn
        ? 'REQUESTED'
        : 'NOT_DUE'
  return {
    id: `ms-${challenge}-${order}`,
    challengeId: `ch-${challenge}`,
    order,
    title,
    deliverable,
    dueOn,
    paymentPct,
    amountLakh: Math.round(valueLakh * paymentPct) / 100,
    status,
    submittedOn: dates.submittedOn ?? null,
    acceptedOn: dates.acceptedOn ?? null,
    payment,
    requestedOn: dates.requestedOn ?? null,
    approvedOn: dates.approvedOn ?? null,
    paidOn: dates.paidOn ?? null,
  }
}

