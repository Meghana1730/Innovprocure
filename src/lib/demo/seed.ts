let eventCount = 0
function event(
  challenge: string,
  on: string,
  role: TimelineEvent['role'],
  actor: string,
  action: string,
  detail = '',
): TimelineEvent {
  eventCount += 1
  return { id: `ev-${eventCount}`, challengeId: `ch-${challenge}`, on, role, actor, action, detail }
}

// The entries below are built from the seeded scores, milestones and readings, with the same
// wording the live actions write, so the seeded trails cannot disagree with the records.

/** One "Score submitted" entry per seeded score of a challenge. */
function scoreEvents(challenge: string): TimelineEvent[] {
  return SCORES.filter((s) => s.applicationId.startsWith(`app-${challenge}-`)).map((s) => {
    const startupId = APPLICATIONS.find((a) => a.id === s.applicationId)?.startupId
    return event(
      challenge,
      s.submittedOn,
      'evaluator',
      EVALUATORS.find((e) => e.id === s.evaluatorId)?.name ?? 'Evaluator',
      'Score submitted',
      STARTUPS.find((x) => x.id === startupId)?.name ?? '',
    )
  })
}

/** Submitted, accepted, payment approved and paid entries for every milestone of a challenge. */
function milestoneEvents(challenge: string, startupName: string): TimelineEvent[] {
  return MILESTONES.filter((m) => m.challengeId === `ch-${challenge}`).flatMap((m) => {
    const amount = fmtLakh(m.amountLakh)
    const out: TimelineEvent[] = []
    if (m.submittedOn)
      out.push(
        event(
          challenge,
          m.submittedOn,
          'startup',
          startupName,
          `Milestone ${m.order} submitted`,
          m.title,
        ),
      )
    if (m.acceptedOn)
      out.push(
        event(
          challenge,
          m.acceptedOn,
          'department',
          'Demo Department Officer',
          `Milestone ${m.order} accepted`,
          `Payment request of ${amount} raised automatically`,
        ),
      )
    if (m.approvedOn)
      out.push(
        event(
          challenge,
          m.approvedOn,
          'finance',
          'Demo Finance Officer',
          `Milestone ${m.order} payment approved`,
          amount,
        ),
      )
    if (m.requestedOn && m.paidOn)
      out.push(
        event(
          challenge,
          m.paidOn,
          'finance',
          'Demo Finance Officer',
          `Milestone ${m.order} paid`,
          `${amount}, ${plural(daysBetween(m.requestedOn, m.paidOn), 'day')} after the request`,
        ),
      )
    return out
  })
}

/** One "KPI readings recorded" entry per pilot week that has seeded readings. */
function readingEvents(challenge: string): TimelineEvent[] {
  const pilot = PILOTS.find((p) => p.challengeId === `ch-${challenge}`)
  if (!pilot) return []
  const weeks = new Set(
    MEASUREMENTS.filter((m) => m.challengeId === pilot.challengeId).map((m) => m.week),
  )
  return [...weeks]
    .sort((a, b) => a - b)
    .map((week) =>
      event(
        challenge,
        addDays(pilot.startOn, week * 7),
        'department',
        'Demo Department Officer',
        `KPI readings recorded for week ${week}`,
      ),
    )
}

